"""Typed models and interfaces for Stage B Decipherment operations.

Note: As per Day 1 specification, these define the typed contracts and interfaces
for Stage B. Advanced decipherment execution is scheduled for subsequent days.
"""
from enum import Enum
from typing import Dict, List, Optional, Protocol, Tuple, runtime_checkable
from pydantic import BaseModel, Field


class BandhaPattern(str, Enum):
    """Known poetic/geometric bandhas used in Siri Bhoovalaya decipherment."""
    SARVATOBHADRA = "SARVATOBHADRA"
    PADMABANDHA = "PADMABANDHA"
    GOMUTRIKA = "GOMUTRIKA"
    CHAKRABANDHA = "CHAKRABANDHA"
    RATHABANDHA = "RATHABANDHA"
    NAGABANDHA = "NAGABANDHA"
    CHATURANGA = "CHATURANGA"
    KSHETRABANDHA = "KSHETRABANDHA"
    GARUDABANDHA = "GARUDABANDHA"


class CoordinateStep(BaseModel):
    """Single step in a 27x27 matrix traversal trajectory."""
    step_number: int
    row: int = Field(..., ge=0, le=26)
    col: int = Field(..., ge=0, le=26)
    cell_value: Optional[int] = None


class TraversalTrajectory(BaseModel):
    """Ordered sequence of coordinate steps generated by a Bandha."""
    bandha_name: BandhaPattern
    steps: List[CoordinateStep]
    total_steps: int
    cycle_length: Optional[int] = None
    properties: Dict[str, str] = Field(default_factory=dict)


class PhoneticMapping(BaseModel):
    """Ankaphala mapping: integer number (1-64) mapped to Halegannada phoneme."""
    number: int = Field(..., ge=1, le=64)
    primary_akshara: str
    vowel_matra: Optional[str] = None
    ipa_transcription: Optional[str] = None
    iast_transliteration: Optional[str] = None


class AlignedVerseCandidate(BaseModel):
    """Candidate verse produced after phonetic substitution and meter alignment."""
    raw_character_stream: str
    segmented_verse: str
    meter_score: float = Field(..., ge=0.0, le=1.0)
    language_probability: Dict[str, float] = Field(default_factory=dict)
    candidate_id: str


class DeciphermentExplanation(BaseModel):
    """Bilingual historical explanation of a deciphered passage."""
    passage_id: str
    verse_text: str
    english_translation: str
    english_historical_context: str
    modern_kannada_translation: str
    modern_kannada_commentary: str
    historical_entities_referenced: List[str] = Field(default_factory=list)
    confidence_score: float = 1.0


class DeciphermentRequest(BaseModel):
    """Request to initiate Stage B decipherment on an extracted Chakra."""
    chakra_id: str
    selected_bandha: BandhaPattern
    start_coordinate: Tuple[int, int] = (13, 13)  # Center cell of 27x27 grid
    custom_parameters: Dict[str, str] = Field(default_factory=dict)


class DeciphermentResult(BaseModel):
    """Output of a decipherment pipeline execution."""
    job_id: str
    chakra_id: str
    bandha: BandhaPattern
    trajectory: TraversalTrajectory
    raw_numerical_sequence: List[int]
    phonetic_akshara_sequence: str
    aligned_verse: AlignedVerseCandidate
    explanation: DeciphermentExplanation
    is_partial: bool = False

